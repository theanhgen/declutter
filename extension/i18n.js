// The extension's own pages, the chip and the badge tooltip in the browser's UI language: Czech when it is Czech,
// English otherwise (#25). One small table, no _locales. The English is the text the pages already carry inline (their
// fallback; test/unit.test.mjs checks the two agree), the Czech sits beside it. A value is a string with {name}
// slots, or a function for counted words. HTML pages mark translatable elements data-i18n="key"; {0}, {1}… in a value
// stand for that element's child elements, in order, kept as they are (links, inputs, switches; they may carry keys
// of their own).

// The browser's UI language, else the page's. Not the site's: a Czech site in an English browser stays English here.
function uiLanguage() {
  try {
    const api = globalThis.browser ?? globalThis.chrome;
    return api?.i18n?.getUILanguage?.() || globalThis.navigator?.language || '';
  } catch { return ''; }
}
