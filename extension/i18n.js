// The text for key in the UI language (English where Czech has none), with {name} slots filled from vars.
export function t(key, vars = {}) {
  const s = STRINGS[LANG][key] ?? STRINGS.en[key];
  if (s === undefined) return key;
  return typeof s === 'function' ? s(vars) : s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// Puts the UI language on a page: every [data-i18n] element gets its text, its child elements kept in the {n} slots.
// English pages are left as written.
export function applyI18n(doc = document) {
  if (LANG === 'en') return;
  doc.documentElement.lang = LANG;
  for (const el of doc.querySelectorAll('[data-i18n]')) {
    const kids = [...el.children];
    el.replaceChildren(...t(el.dataset.i18n).split(/\{(\d+)\}/).map((part, i) => (i % 2 ? kids[Number(part)] : part)).filter((p) => p !== '' && p !== undefined));
  }
}
